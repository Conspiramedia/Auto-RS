// ============================================================
// AUTO.RS — Custom Function для FlutterFlow: generateTempUuid
// ============================================================
// Генерирует временный UUID v4 на КЛИЕНТЕ для имени папки машины
// в пути загрузки фото (до того, как БД создаст реальный car_id).
//
// Зачем: реальный UUID машины появляется только после вызова create_car_v2,
// а фото нужно загрузить РАНЬШЕ (чтобы передать их ссылки в RPC). Поэтому
// на этапе загрузки используем временный UUID как имя подпапки.
//
// -----------------------------------------------------------------
// НАСТРОЙКА ВО FLUTTERFLOW (Custom Function):
//   Имя: generateTempUuid
//   Return Type: String (не nullable)
//   Arguments: нет
//
// Пакет: uuid (добавить в pubspec: uuid: ^4.4.0). FlutterFlow сам подтянет
// зависимость при добавлении её в Custom Function → Dependencies.
// -----------------------------------------------------------------

import 'package:uuid/uuid.dart';

String generateTempUuid() {
  // v4 — случайный UUID; достаточно уникален для имени папки загрузки
  return const Uuid().v4();
}
