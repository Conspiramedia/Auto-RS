// Зеркало lib/plural.ts сайта: логика перенесена дословно, чтобы
// «Найдено: 11 объявлений» читалось одинаково в обоих клиентах.
//
// «11 объявление» и «29 объявления» — это не мелочь: такие подписи
// стоят рядом с крупными цифрами и сразу выдают машинный текст.
//
// Русский и сербский относятся к одной славянской группе и используют
// ОДНО правило множественного числа (CLDR-категории one / few / many):
//   one  — 1, 21, 31, 101…       но НЕ 11
//   few  — 2-4, 22-24, 32-34…    но НЕ 12-14
//   many — 0, 5-20, 25-30, 11-14…
//
// Исключение 11-14 — то самое место, где обычно ошибаются: 11
// оканчивается на 1, но берёт форму «объявлений», а не «объявление».
//
// Пакет intl даёт те же категории из данных CLDR, но собственная
// реализация здесь надёжнее: она не зависит от того, какие локали
// собраны в среде выполнения, и её поведение видно прямо в коде.
// В этом проекте у intl есть и отдельная причина: русской локали в нём
// нет, DateFormat('ru') падает в рантайме. [[intl-no-russian-locale]]
// ============================================================

/// Три формы существительного для одного языка.
class PluralForms {
  const PluralForms({
    required this.one,
    required this.few,
    required this.many,
  });

  /// 1 объявление / 1 oglas
  final String one;

  /// 2 объявления / 2 oglasa
  final String few;

  /// 5 объявлений / 5 oglasa
  final String many;
}

/// Категория по числу. Правило общее для ru и sr.
String _pluralCategory(int n) {
  final abs = n.abs();
  final mod10 = abs % 10;
  final mod100 = abs % 100;

  // 11-14 всегда «many», несмотря на последнюю цифру.
  if (mod100 >= 11 && mod100 <= 14) return 'many';
  if (mod10 == 1) return 'one';
  if (mod10 >= 2 && mod10 <= 4) return 'few';
  return 'many';
}

/// Выбор формы слова БЕЗ самого числа.
String pluralize(int n, PluralForms forms) {
  switch (_pluralCategory(n)) {
    case 'one':
      return forms.one;
    case 'few':
      return forms.few;
    default:
      return forms.many;
  }
}

/// Число вместе с нужной формой: «11 объявлений».
String withPlural(int n, PluralForms forms) => '$n ${pluralize(n, forms)}';
