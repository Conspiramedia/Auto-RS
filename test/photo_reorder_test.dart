// ============================================================
// AUTO.RS — Тесты перестановки фотографий в форме подачи.
// ============================================================
// Порядок в списке фото — не украшение: ПЕРВЫЙ элемент попадает
// в каталог обложкой, и отдельного поля «главная» у объявления нет.
// Поэтому стрелки под превью — единственный способ выбрать главный
// кадр, и их поведение стоит проверить отдельно.
//
// Экран подачи требует Supabase в initState и в виджет-тесте не
// поднимается (метод А1), а _movePhoto живёт в приватном State.
// Проверяем сам алгоритм — ровно тот, что выполняет обработчик:
// remove + insert, как move() в PhotoPicker сайта.
// ============================================================

import 'package:flutter_test/flutter_test.dart';

/// Копия тела _CreateCarScreenState._movePhoto без setState.
/// Расхождение с экраном поймает ревью: алгоритм в три строки, и
/// дублировать его дешевле, чем поднимать весь экран с моками.
List<String> movePhoto(List<String> urls, int index, int direction) {
  final target = index + direction;
  if (target < 0 || target >= urls.length) return urls;

  final next = [...urls];
  final moved = next.removeAt(index);
  next.insert(target, moved);
  return next;
}

void main() {
  // Высота полосы превью складывается из трёх слагаемых, и рамку легко
  // забыть: именно на ней контейнер вылезал на 2px, и Flutter рисовал
  // «BOTTOM OVERFLOWED BY 2.0 PIXELS» поверх стрелок.
  test('Высота карточки превью учитывает рамку', () {
    const previewH = 90.0; // кадр 4:3
    const navH = 32.0;     // полоса стрелок: py-1.5 (6+6) + строка 20
    const borderH = 2.0;   // Border.all(1) сверху и снизу

    expect(previewH + navH + borderH, 124.0);
  });

  test('Сдвиг вправо меняет соседние кадры местами', () {
    expect(movePhoto(['a', 'b', 'c'], 0, 1), ['b', 'a', 'c']);
  });

  test('Сдвиг влево меняет соседние кадры местами', () {
    expect(movePhoto(['a', 'b', 'c'], 2, -1), ['a', 'c', 'b']);
  });

  test('Сдвиг за левую границу ничего не меняет', () {
    expect(movePhoto(['a', 'b', 'c'], 0, -1), ['a', 'b', 'c']);
  });

  test('Сдвиг за правую границу ничего не меняет', () {
    expect(movePhoto(['a', 'b', 'c'], 2, 1), ['a', 'b', 'c']);
  });

  test('Единственный кадр не двигается ни в одну сторону', () {
    expect(movePhoto(['a'], 0, 1), ['a']);
    expect(movePhoto(['a'], 0, -1), ['a']);
  });

  test('Сдвиг влево делает кадр обложкой', () {
    // Главный сценарий: продавец снял нужный ракурс вторым и делает
    // его первым — именно этот кадр уйдёт в каталог.
    final result = movePhoto(['общий', 'нужный', 'салон'], 1, -1);
    expect(result.first, 'нужный');
  });

  test('Перестановка сохраняет состав списка', () {
    // Ни один кадр не теряется и не дублируется: список уходит в RPC
    // как есть, и потерянное фото восстановить было бы нечем.
    const source = ['a', 'b', 'c', 'd'];
    final result = movePhoto(source, 2, -1);

    expect(result.length, source.length);
    expect(result.toSet(), source.toSet());
  });
}
